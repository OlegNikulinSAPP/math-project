def make_matrix(n: int) -> list[list[int]]:
    """Формирует матрицу N x N, заполненную по спирали по часовой стрелке"""

    matrix = [[0] * n for _ in range(n)]

    # Задаем смещение по строке и столбцу. Индекс в списках - это номер направления:
    # 0 - вправо, 1 - вниз, 2 - влево, 3 - вверх
    dx = [0, 1, 0, -1]
    dy = [1, 0, -1, 0]

    # Задаем стартовую позицию - левый верхний угол матрицы
    x, y = 0, 0

    # Задаем начальное направление движения d = 0 - это "вправо"
    d = 0

    for num in range(1, n * n + 1):
        # записываем текущее число в ячейку
        matrix[x][y] = num

        # вычисляем координаты ячейки, в которую хотим шагнуть (nx, ny):
        # берем текущую позицию и прибавляем вектор смещения для текущего направления d
        nx, ny = x + dx[d], y + dy[d]

        # проверяем, можно ли шагнуть в ячейку (nx, ny):
        # not (0 <= nx < N and 0 <= ny < N) - ячейка за границей диапазона
        # matrix[nx][ny] != 0 - ячейка уже занята
        if not (0 <= nx < n and 0 <= ny < n) or matrix[nx][ny] != 0:
            # поворачиваем: увеличиваем номер направления на 1.
            # Операция % 4 обеспечивает "закольцованность" - после 3 (вверх) снова идет 0 (вправо)
            d = (d + 1) % 4

            # пересчитываем координаты
            nx, ny = x + dx[d], y + dy[d]

        # перемещаемся в следующую ячейку
        x, y = nx, ny

    return matrix


def print_matrix(matrix: list[list[int]]) -> None:
    """Вывод матрицы"""
    width = len(str(max(max(row) for row in matrix)))
    for row in matrix:
        print(' '.join(f'{num:>{width}}' for num in row))


def main():
    n = int(input())
    matrix = make_matrix(n)
    print_matrix(matrix)


if __name__ == "__main__":
    main()
